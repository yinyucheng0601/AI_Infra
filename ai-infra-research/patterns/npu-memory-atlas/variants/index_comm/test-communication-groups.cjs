const assert=require('node:assert/strict');
const fs=require('node:fs'),vm=require('node:vm');
const html=fs.readFileSync(require('node:path').join(__dirname,'../index_communication.html'),'utf8');
const EPTeachingModel=require('./ep-model.js');
const extract=(start,end)=>html.slice(html.indexOf(start),html.indexOf(end,html.indexOf(start)));
const context={EPTeachingModel,Map,atlasConfig:{cp:1,etp:1,seq:32,mbs:1,topk:2},TP:2,PP:4,DP:16,EP:8,ETP:1,L:48,EXPERTS:64,HBM:64,epEventCache:new Map(),ranks:Array.from({length:128},(_,id)=>({id,pp:Math.floor(id/32)})),RankAtlasModel:{moeLayer:()=>7}};
vm.createContext(context);
vm.runInContext(extract('function communicationMembers(', 'function drawEPSpatialSankey(')+extract('function epEventAt(', 'function incidentAt('),context);
const members=id=>Array.from(context.communicationMembers(id));
assert.deepEqual(members(23),[16,17,18,19,20,21,22,23]);
assert.deepEqual(members(48),[48,49,50,51,52,53,54,55]);
context.EP=16;assert.deepEqual(members(23),Array.from({length:16},(_,i)=>16+i));
context.EP=8;context.atlasConfig.etp=2;assert.deepEqual(members(23),[17,19,21,23,25,27,29,31]);
context.atlasConfig.etp=1;context.atlasConfig.cp=2;assert.deepEqual(members(71),[64,65,66,67,68,69,70,71]);
context.atlasConfig.cp=1;
const e=context.epEventAt(0,23).event;
assert.deepEqual(Array.from(e.ids),members(23));
assert(e.flows.some(f=>f.source%2!==f.target%2&&f.tokens>0));
assert(e.flows.every(f=>e.ids.includes(f.source)&&e.ids.includes(f.target)));
assert.equal(EPTeachingModel.trace(e,.3,23).buckets.length,8);
const frame=EPTeachingModel.frame(e,.85);assert.equal(frame.ranks.length,8);
assert.equal(e.flows.reduce((n,f)=>n+f.tokens,0),e.totalTokens);
console.log('PASS: config-driven EP/ETP/CP groups, mapped flows, cross-column traffic and token conservation');

vm.runInContext(extract('function scopedTraffic(', 'function drawEPSpatialSankey('),context);
const window={start:.16,end:.44,direction:'out',all:false};
const full=context.trafficWindowFlows(e,23,window);
assert(full.length>0&&full.every(f=>f.source===23));
const early=context.trafficWindowFlows(e,23,{...window,end:.3});
assert(early.reduce((n,f)=>n+f.tokens,0)<full.reduce((n,f)=>n+f.tokens,0));
const incoming=context.trafficWindowFlows(e,23,{...window,direction:'in'});assert(incoming.every(f=>f.target===23));
const combine=context.trafficWindowFlows(e,23,{...window,start:.7,end:1,direction:'in'});assert.equal(combine.reduce((n,f)=>n+f.tokens,0),full.reduce((n,f)=>n+f.tokens,0));
console.log('PASS: rank selection, incoming/outgoing scope, time aggregation and Combine reversal');
